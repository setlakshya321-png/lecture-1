def make_index(columns, index_name):
    scaled = StandardScaler().fit_transform(df[columns])
    pca = PCA().fit(scaled)
    scores = pca.transform(scaled)[:, 0]

    sign = 1 if pca.components_[0].sum() > 0 else -1
    scores = scores * sign

    df[index_name] = (scores - scores.min()) / (scores.max() - scores.min()) * 100
    variance_explained[index_name] = round(pca.explained_variance_ratio_[0] * 100)

